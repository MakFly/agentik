const CONFIG_EXEMPT = new Set(["probe", "context", "postmortem"]);
const KNOWN_COMMANDS = new Set(["probe", "spawn", "memory", "skill", "skills", "harvest", "context", "review", "postmortem", "run"]);

/** Exit 2 with the depth message; the refusal is an incident so the conductor sees it next time. */
async function refuseNested(cmd: "spawn" | "run", argv: string[]): Promise<number> {
  const problem = depthProblem(cmd)!;
  console.error(`agentik: ${problem}`);
  const parsed = parseRun(argv);
  const workspace = resolve(parsed.flags.workspace ?? process.cwd());
  try {
    const rec = await recordIncident(
      {
        goal: parsed.goal || parsed.flags.goalFlag || `agentik ${cmd}`,
        workspace,
        profile: parsed.flags.profile ?? process.env.AGENTIK_PROFILE ?? "default",
        harness: "agentik",
        backend: parsed.flags.harness ?? parsed.flags.backend ?? "",
        exitCode: 2,
        stopReason: "nested",
        errors: [problem],
        symptom: nestedSymptom(cmd),
      },
      { home: homeFromArgv(argv) },
    );
    console.error(`agentik: incident #${rec.id} recorded (seen ${rec.seen}×, depth ${currentDepth()})`);
  } catch (err) {
    console.error(`agentik: could not record incident: ${err instanceof Error ? err.message : String(err)}`);
  }
  return 2;
}

/** The home the command will use, from the raw argv (before any subcommand parses its flags). */
function homeFromArgv(argv: string[]): string {
  let agentikHomeFlag: string | undefined;
  let profile: string | undefined;
  for (let i = 0; i < argv.length - 1; i++) {
    if (argv[i] === "--agentik-home") agentikHomeFlag = argv[i + 1];
    else if (argv[i] === "--profile") profile = argv[i + 1];
  }
  return homeFor({ agentikHome: agentikHomeFlag, profile });
}

/** Exit code when `<home>/config.json` is unusable, `undefined` when it is fine or absent. */
async function preflightConfig(argv: string[]): Promise<number | undefined> {
  try {
    await readConfig({ home: homeFromArgv(argv) });
    return undefined;
  } catch (err) {
    if (err instanceof ConfigError) {
      console.error(`agentik: ${formatConfigError(err)}`);
      return 2;
    }
    throw err;
  }
}

/** `--timeout 0` is meaningful (no bound), so 0 must survive the parse. */
function nonNegative(v: string | boolean | undefined): number | undefined {
  if (typeof v !== "string") return undefined;
  const n = Number(v);
  return Number.isFinite(n) && n >= 0 ? n : undefined;
}

const HARVEST_USAGE =
  'usage: agentik harvest "<goal>" [--workspace DIR] [--artifact PATH] [--step TEXT] [--transcript FILE]\n' +
  "       [--status completed|failed|partial] [--cause TEXT]   (failed|partial require --cause)";

const HARVEST_STATUSES = new Set<SessionStatus>(["completed", "failed", "partial"]);

async function harvestCmd(args: string[]): Promise<number> {
  const { goal, flags } = parseRun(args);
  const harvestGoal = goal || flags.goalFlag || "";
  if (!harvestGoal) {
    console.error(HARVEST_USAGE);
    return 2;
  }
  const status = (flags.status ?? "completed") as SessionStatus;
  if (!HARVEST_STATUSES.has(status)) {
    console.error(`agentik harvest: --status must be completed, failed or partial (got "${flags.status}")`);
    console.error(HARVEST_USAGE);
    return 2;
  }
  const cause = flags.cause?.trim() ?? "";
  if (status !== "completed" && !cause) {
    console.error(`agentik harvest: --status ${status} — a failure needs a cause (--cause TEXT)`);
    console.error(HARVEST_USAGE);
    return 2;
  }
  const artifacts: string[] = [];
  const steps: string[] = [];
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--artifact" && args[i + 1]) artifacts.push(args[++i]);
    if (args[i] === "--step" && args[i + 1]) steps.push(args[++i]);
  }
  const executedTools = steps.map((s) => {
    const [tool, artifact] = s.split("->").map((x) => x.trim());
    return { tool: tool || "step", args: {}, output: s, artifact };
  });
  const workspace = resolve(flags.workspace ?? process.cwd());
  const harvested = await reviewAfterRun({
    goal: harvestGoal,
    report: {
      status,
      executedTools,
      artifacts,
    },
    home: homeFor(flags),
    // The help says "default: cwd"; a blank workspace would hide this session from every
    // workspace-filtered search.
    workspace,
    profile: flags.profile,
  });
  console.log(`memory: ${harvested.memoryLayer} #${harvested.sessionId}`);
  if (status !== "completed") {
    // The conductor named the cause; that is the symptom until a postmortem classifies it.
    // The session is already recorded; a failure to log the incident must not undo that.
    try {
      const rec = await recordIncident(
        {
          goal: harvestGoal,
          workspace,
          profile: flags.profile ?? process.env.AGENTIK_PROFILE ?? "default",
          harness: undefined,
          errors: [],
          symptom: cause,
        },
        { home: homeFor(flags) },
      );
      console.log(`incident: #${rec.id} recorded (seen ${rec.seen}×) — agentik postmortem review ${rec.id}`);
    } catch (err) {
      console.error(`agentik harvest: could not record incident: ${err instanceof Error ? err.message : String(err)}`);
    }
  }
  if (flags.transcript && !flags.noReview) {
    // The conductor wrote down what happened; hand it to the reviewer in the same call.
    return reviewCmd([
      harvestGoal,
      "--transcript",
      flags.transcript,
      "--workspace",
      flags.workspace ?? process.cwd(),
      ...(flags.agentikHome ? ["--agentik-home", flags.agentikHome] : []),
      ...(flags.profile ? ["--profile", flags.profile] : []),
      ...(flags.backend ? ["--backend", flags.backend] : []),
    ]);
  }
  console.log("skill: none here — the model-driven review decides (agentik review, or harvest --transcript FILE)");
  return 0;
}

const MEMORY_USAGE =
  'usage: agentik memory search "<query>" [--workspace DIR] [--all] [--limit N] | recall (alias)\n' +
  '       agentik memory hot | retain <fact> | remove "<exact entry or unique prefix>"  [--target memory|user|project] [--workspace DIR]\n' +
  "       agentik memory pending | approve <id|all> | reject <id|all>";

/** `--target` (default memory); `project` scopes to `--workspace` or the cwd. */
function memoryTargetFor(flags: { target?: string; workspace?: string }): { target: MemoryTarget; workspace?: string } | { error: string } {
  const raw = flags.target ?? "memory";
  if (raw !== "memory" && raw !== "user" && raw !== "project") {
    return { error: `unknown --target "${raw}" (memory | user | project)` };
  }
  return { target: raw, workspace: raw === "project" ? resolve(flags.workspace ?? process.cwd()) : undefined };
}

async function memoryCmd(args: string[]): Promise<number> {
  const sub = args[0];
  const { goal, flags } = parseRun(args.slice(1));
  const home = homeFor(flags);
  if (sub === "hot" || sub === "retain" || sub === "remove") {
    const scope = memoryTargetFor(flags);
    if ("error" in scope) {
      console.error(`agentik memory ${sub}: ${scope.error}`);
      return 2;
    }
    const { target, workspace } = scope;
    if (sub === "hot") {
      if (target === "memory") {
        process.stdout.write((await readHot({ home })) || "(empty HOT MEMORY.md)\n");
        return 0;
      }
      let body = "";
      try {
        body = await readFile(memoryFilePath(target, { home, workspace }), "utf8");
      } catch {
        body = "";
      }
      process.stdout.write(body || `(empty ${memoryFileLabel(target)}${workspace ? ` for ${workspace}` : ""})\n`);
      return 0;
    }
    if (!goal) {
      console.error(sub === "retain" ? "usage: agentik memory retain <note> [--target memory|user|project] [--workspace DIR]" : MEMORY_USAGE);
      return 2;
    }
    if (sub === "retain") {
      const r = await retainNote(goal, { home, target, workspace });
      console.log(r.layer === "rejected" ? `rejected: ${r.reason}` : `${r.layer} ${r.path}`);
      if (r.layer === "pending") console.log(`memory.writeApproval is on — ${r.reason}`);
      return r.layer === "rejected" ? 3 : 0;
    }
    // remove: the human's pen — no approval queue, a backup first, exact or unique-prefix match.
    const r = await memoryRemoveEntry(target, goal, { home, workspace });
    if (!r.ok) {
      console.error(`agentik memory remove: ${r.message}`);
      for (const c of r.candidates) console.error(`  § ${c}`);
      return 1;
    }
    console.log(`removed: ${r.removed}`);
    console.log(`backup: ${r.backup}`);
    console.log(`${memoryFileLabel(target)} ${r.usage.used}/${r.usage.cap} chars`);
    return 0;
  }
  if (sub === "pending") {
    console.log(formatPendingMemory(await listPending<PendingMemoryOp>("memory", { home })));
    return 0;
  }
  if (sub === "approve" || sub === "reject") {
    const id = args[1];
    if (!id) {
      console.error(MEMORY_USAGE);
      return 2;
    }
    const res = sub === "approve" ? await approveMemory(id, { home }) : await rejectPending("memory", id, { home });
    if ("error" in res) {
      console.error(`agentik memory ${sub}: ${res.error}`);
      return 1;
    }
    return printOutcomes(`memory ${sub}`, res);
  }
  if (sub === "search" || sub === "recall") {
    if (!goal) {
      console.error(MEMORY_USAGE);
      return 2;
    }
    const hits = await searchSessions(goal, {
      home,
      workspace: flags.workspace,
      all: flags.all,
      limit: flags.limit ?? 6,
    });
    console.log(hits.length ? hits.map((h) => `- ${formatSessionHit(h)}`).join("\n") : "(no hits)");
    return 0;
  }
  console.error(MEMORY_USAGE);
  return 2;
}

/** The block `/ak` reads at session open. `--workspace` scopes the related sessions. */
async function contextCmd(args: string[]): Promise<number> {
  const { goal, flags } = parseRun(args);
  const block = await buildContext({
    home: homeFor(flags),
    workspace: flags.workspace ? resolve(flags.workspace) : undefined,
    goal: goal || flags.goalFlag,
  });
  process.stdout.write(block);
  return 0;
}

const SKILL_USAGE =
  "usage: agentik skill list | view <name> | draft <name> --description \"…\" <goal> | approve <name> [--link-harness] | update <name> <goal>\n" +
  "       agentik skills unlink | archive | pin <name> | unpin <name> | link <name>\n" +
  "       agentik skills curate [--dry-run] [--stale-days N] [--archive-days N] [--rollback SNAPSHOT]\n" +
  "       agentik skills pending | approve <id|all> | reject <id|all>";

async function skillCmd(args: string[]): Promise<number> {
  const sub = args[0];
  const { goal, flags } = parseRun(args.slice(1));
  const home = homeFor(flags);
  if (sub === "list") {
    const [{ pending, approved, archived, pinned }, usage, counts] = await Promise.all([
      listSkills({ home }),
      readSkillUsage({ home }),
      pendingCounts({ home }),
    ]);
    console.log(`pending: ${pending.join(", ") || "(none)"}`);
    console.log(approved.length ? "approved:" : "approved: (none)");
    for (const name of approved) console.log(`  - ${name} [${describeUsage(usage[name])}]`);
    console.log(`pinned: ${pinned.join(", ") || "(none)"}`);
    console.log(`archived: ${archived.length}${archived.length ? ` (${archived.join(", ")})` : ""}`);
    if (counts.skills) console.log(`pending skill ops: ${counts.skills} (agentik skills pending)`);
    return 0;
  }
  if (sub === "view") {
    const name = args[1];
    if (!name) {
      console.error(SKILL_USAGE);
      return 2;
    }
    const body = await viewSkill(name, { home });
    if (body === undefined) {
      console.error(`agentik skills view: no skill named ${name}`);
      return 1;
    }
    process.stdout.write(body.endsWith("\n") ? body : `${body}\n`);
    return 0;
  }
  if (sub === "curate") {
    if (flags.rollback) {
      const r = await rollbackSkills(flags.rollback, { home });
      if ("error" in r) {
        console.error(`agentik skills curate --rollback: ${r.error}`);
        return 1;
      }
      console.log(`rollback: restored ${r.restored} — safety snapshot ${r.safetySnapshot}`);
      return 0;
    }
    const result = await curateSkills({ home, dryRun: flags.dryRun, staleDays: flags.staleDays, archiveDays: flags.archiveDays });
    console.log(formatCurateResult(result));
    return 0;
  }
  if (sub === "pending") {
    console.log(formatPendingSkills(await listPending<PendingSkillOp>("skills", { home })));
    return 0;
  }
  if (sub === "reject") {
    const id = args[1];
    if (!id) {
      console.error(SKILL_USAGE);
      return 2;
    }
    const res = await rejectPending("skills", id, { home });
    if ("error" in res) {
      console.error(`agentik skills reject: ${res.error}`);
      return 1;
    }
    return printOutcomes("skills reject", res);
  }
  if (sub === "draft") {
    const name = args[1];
    const rest = parseRun(args.slice(2));
    if (!name || !rest.goal || !rest.flags.description) {
      console.error(SKILL_USAGE);
      return 2;
    }
    const problem = skillNameProblem(name);
    if (problem) {
      console.error(`agentik: invalid skill name "${name}": ${problem} — names are class-level, not session titles`);
      return 2;
    }
    try {
      const drafted = await draftSkill({
        name,
        description: rest.flags.description,
        goal: rest.goal,
        steps: ["Captured from CLI draft."],
        home: rest.flags.agentikHome ? homeFor(rest.flags) : home,
      });
      console.log(drafted.path);
      return 0;
    } catch (err) {
      console.error(`agentik: ${err instanceof Error ? err.message : String(err)}`);
      return 2;
    }
  }
  if (sub === "approve") {
    const name = args[1];
    if (!name) {
      console.error(SKILL_USAGE);
      return 2;
    }
    // `approve all` / `approve <id>` is the staged-op queue; `approve <name>` a human draft.
    if (name === "all" || (isPendingId(name) && (await readPending("skills", name, { home })))) {
      const res = await approveSkillOps(name, { home });
      if ("error" in res) {
        console.error(`agentik skills approve: ${res.error}`);
        return 1;
      }
      return printOutcomes("skills approve", res);
    }
    // Linking is opt-in: a linked skill sits in every prompt of every harness, every turn.
    const ok = await approveSkill(name, { home, linkHarness: flags.linkHarness });
    if ("error" in ok) {
      console.error(ok.error);
      return 1;
    }
    await recordSkillUsage(name, "create", { home, createdBy: "human" });
    console.log(ok.path);
    return 0;
  }
  if (sub === "unlink") {
    const { removed, kept } = await unlinkHarnessSkills({ home });
    console.log(`unlinked ${removed.length} harness symlink(s); kept ${kept.length} pinned`);
    for (const r of removed) console.log(`  - ${r}`);
    return 0;
  }
  if (sub === "archive") {
    const { archived, kept } = await archiveAutoGeneratedSkills({ home });
    console.log(`archived ${archived.length} auto-generated skill(s) into skills/.archive; kept ${kept.join(", ") || "(none)"}`);
    for (const a of archived) console.log(`  - ${a}`);
    return 0;
  }
  if (sub === "pin" || sub === "unpin") {
    const name = args[1];
    if (!name) {
      console.error(SKILL_USAGE);
      return 2;
    }
    if (sub === "pin") {
      // Pinning is bookkeeping, not a prompt load: warn, do not refuse.
      const warn = await skillBodyProblem(name, home);
      if (warn) console.error(`agentik skills pin: warning — ${name}: ${warn} (link will be refused)`);
    }
    const pinned = await pinSkill(name, { home, unpin: sub === "unpin" });
    console.log(`pinned: ${pinned.join(", ") || "(none)"}`);
    return 0;
  }
  if (sub === "link") {
    const name = args[1];
    if (!name) {
      console.error(SKILL_USAGE);
      return 2;
    }
    const dir = join(memoryPaths(agentikHome(home)).skills, name);
    let linked: string[];
    try {
      linked = await linkHarnessSkill(name, dir);
    } catch (err) {
      console.error(`agentik skills link: ${err instanceof Error ? err.message : String(err)}`);
      return 1;
    }
    console.log(`linked ${name} into ${linked.length} harness home(s)`);
    return 0;
  }
  if (sub === "update") {
    const name = args[1];
    const rest = args.slice(2);
    const parsed = parseRun(rest);
    const updateGoal = parsed.goal;
    if (!name || !updateGoal) {
      console.error("usage: agentik skill update <name> <goal>");
      return 2;
    }
    const ok = await updateSkill(
      name,
      { goal: updateGoal, steps: [`Updated from CLI: ${updateGoal}`] },
      { home: parsed.flags.agentikHome ? homeFor(parsed.flags) : home },
    );
    if ("error" in ok) {
      console.error(ok.error);
      return 1;
    }
    await recordSkillUsage(name, "patch", { home: parsed.flags.agentikHome ? homeFor(parsed.flags) : home });
    console.log(ok.path);
    return 0;
  }
  console.error(SKILL_USAGE);
  return 2;
}

